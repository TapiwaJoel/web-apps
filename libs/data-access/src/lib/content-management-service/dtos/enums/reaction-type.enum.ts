/**
 * Enum representing available reaction types for content engagement
 */
export enum ReactionType {
  /**
   * Positive endorsement reaction
   */
  LIKE = 'LIKE',

  /**
   * Strong positive feeling reaction
   */
  LOVE = 'LOVE',

  /**
   * Supportive or empathetic reaction
   */
  CARE = 'CARE',

  /**
   * Humorous or funny reaction
   */
  HAHA = 'HAHA',

  /**
   * Surprised or impressed reaction
   */
  WOW = 'WOW',

  /**
   * Disappointing or sad reaction
   */
  SAD = 'SAD',

  /**
   * Frustrating or upsetting reaction
   */
  ANGRY = 'ANGRY',

  /**
   * Valuable or educational content reaction
   */
  INSIGHTFUL = 'INSIGHTFUL',

  /**
   * Heartbroken or devastating reaction
   */
  HEARTBREAK = 'HEARTBREAK',

  /**
   * Disagree or negative reaction
   */
  THUMBS_DOWN = 'THUMBS_DOWN',

  /**
   * Incorrect or wrong reaction
   */
  X_MARK = 'X_MARK',

  /**
   * Discard or worthless reaction
   */
  TRASH = 'TRASH',
}
