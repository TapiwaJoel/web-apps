/**
 * Enum representing entity types that can receive reactions
 */
export enum ReactionableType {
  /**
   * Article content type
   */
  ARTICLE = 'Article',

  /**
   * Comment content type
   */
  COMMENT = 'Comment',

  /**
   * Media content type
   */
  MEDIA = 'Media',

  /**
   * Video content type
   */
  VIDEO = 'Video',

  /**
   * Live stream content type
   */
  LIVE_STREAM = 'LiveStream',

  /**
   * Course content type
   */
  COURSE = 'Course',

  /**
   * Subject content type
   */
  SUBJECT = 'Subject',

  /**
   * Topic content type
   */
  TOPIC = 'Topic',
}
